/** Returns [piece, made-up token id] pairs. Unknown characters fall back to their char code. */
export function tokenize(s: string): [string, number][] {
  const out: [string, number][] = [];
  let i = 0;
  while (i < s.length) {
    let best: string | null = null;
    for (const v of VOCAB) if (s.startsWith(v, i) && (!best || v.length > best.length)) best = v;
    if (best) {
      out.push([best, 1000 + VOCAB.indexOf(best) * 37]);
      i += best.length;
    } else {
      out.push([s[i], s.charCodeAt(i)]);
      i++;
    }
  }
  return out;
}
